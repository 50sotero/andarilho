"""Generate scene contracts from the API's Pydantic models.

Writes:
  packages/scene-contract/scene.schema.json   (persistent scene manifest)
  packages/scene-contract/layout.schema.json  (editable layout)
  packages/scene-contract/scene.ts            (TypeScript types for all contracts)
  services/worker/src/andarilho_worker/contracts/*.schema.json (bundled copies)
  services/api/src/andarilho_api/domain/recipes.json (from the worker's pinned recipes)

Run with the API environment:
  uv run --project services/api python scripts/generate-contracts.py [--check]

``--check`` exits non-zero when any generated file is out of date.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "api" / "src"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from andarilho_api.schemas.scene import (  # noqa: E402
    SCHEMA_VERSION,
    DeliveryEnvelope,
    Layout,
    SceneManifest,
)

CONTRACT_DIR = ROOT / "packages" / "scene-contract"
WORKER_CONTRACT_DIR = ROOT / "services" / "worker" / "src" / "andarilho_worker" / "contracts"
HEADER = (
    "// Generated by scripts/generate-contracts.py from services/api Pydantic models.\n"
    "// Do not edit by hand.\n"
)


def worker_recipes() -> dict[str, Any]:
    """Load the worker's pinned recipes (stdlib-only module) without importing the worker."""
    path = ROOT / "services" / "worker" / "src" / "andarilho_worker" / "recipes.py"
    spec = importlib.util.spec_from_file_location("_andarilho_worker_recipes", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return {
        **{
            quality: {
                "name": recipe.name,
                "digest": recipe.digest,
                "stages": [
                    {"stage": st.stage, "capability": st.capability} for st in recipe.stages
                ],
                "params": dict(recipe.params),
            }
            for quality, recipe in module.RECIPES.items()
        },
        "intake": dict(module.INTAKE),
    }


def standalone_schema(model: type, schema_id: str) -> dict[str, Any]:
    schema = model.model_json_schema(by_alias=True, ref_template="#/$defs/{model}")
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": schema_id,
        "x-schema-version": SCHEMA_VERSION,
        **schema,
    }


def ts_literal(value: Any) -> str:
    return json.dumps(value)


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return ts_literal(schema["const"])
    if "enum" in schema:
        return " | ".join(ts_literal(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(s) for s in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("number", "integer"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        item = ts_type(schema.get("items", {}))
        lo, hi = schema.get("minItems"), schema.get("maxItems")
        if lo is not None and lo == hi and lo <= 16:
            return "[" + ", ".join([item] * lo) + "]"
        return f"Array<{item}>" if "|" in item else f"{item}[]"
    if kind == "object":
        if "properties" in schema:
            return inline_object(schema)
        value = ts_type(schema.get("additionalProperties", {}))
        keys = schema.get("propertyNames")
        if keys:
            return f"Partial<Record<{ts_type(keys)}, {value}>>"
        return f"Record<string, {value}>"
    return "unknown"


def inline_object(schema: dict[str, Any], indent: str = "") -> str:
    required = set(schema.get("required", []))
    lines = ["{"]
    for name, prop in schema["properties"].items():
        optional = "" if name in required else "?"
        lines.append(f"{indent}  {name}{optional}: {ts_type(prop)};")
    lines.append(indent + "}")
    return "\n".join(lines)


def typescript(defs: dict[str, Any]) -> str:
    out = [HEADER, f'export const SCHEMA_VERSION = "{SCHEMA_VERSION}";\n']
    for name in sorted(defs):
        schema = defs[name]
        doc = schema.get("description")
        if doc:
            out.append("/** " + " ".join(doc.split()) + " */")
        if schema.get("type") == "object" and "properties" in schema:
            out.append(f"export interface {name} {inline_object(schema)}\n")
        else:
            out.append(f"export type {name} = {ts_type(schema)};\n")
    return "\n".join(out)


def render() -> dict[Path, str]:
    manifest = standalone_schema(SceneManifest, "https://andarilho.dev/schemas/scene/1.0.json")
    layout = standalone_schema(Layout, "https://andarilho.dev/schemas/layout/1.0.json")
    _, combined = models_json_schema(
        [(SceneManifest, "validation"), (Layout, "validation"), (DeliveryEnvelope, "validation")],
        by_alias=True,
        ref_template="#/$defs/{model}",
    )

    def dump(obj: Any) -> str:
        return json.dumps(obj, indent=2, sort_keys=False) + "\n"

    files = {
        CONTRACT_DIR / "scene.schema.json": dump(manifest),
        CONTRACT_DIR / "layout.schema.json": dump(layout),
        CONTRACT_DIR / "scene.ts": typescript(combined["$defs"]),
        WORKER_CONTRACT_DIR / "scene.schema.json": dump(manifest),
        WORKER_CONTRACT_DIR / "layout.schema.json": dump(layout),
        ROOT / "services" / "api" / "src" / "andarilho_api" / "domain" / "recipes.json": dump(
            {"generatedFrom": "services/worker/src/andarilho_worker/recipes.py", **worker_recipes()}
        ),
    }
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    stale = []
    for path, content in render().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Generated contracts are stale; run `pnpm contracts`:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
